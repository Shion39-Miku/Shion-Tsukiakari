test('IP lookup: trusted proxy chain, IPv4/IPv6, private exclusion, cache and unknown fallback', async () => {
  const req = (peer, header) => ({ socket: { remoteAddress: peer }, headers: { 'x-forwarded-for': header } });
  assert.equal(clientIP(req('127.0.0.1', '8.8.8.8')), '127.0.0.1');
  assert.equal(clientIP(req('10.0.0.2', '1.1.1.1, 8.8.8.8, 10.0.0.1'), ['10.0.0.0/8']), '8.8.8.8');
  assert.equal(clientIP(req('::ffff:127.0.0.1', '8.8.8.8'), ['127.0.0.1/32']), '8.8.8.8');
  assert.equal(clientIP(req('::1', 'garbage, 8.8.8.8'), ['::1/128']), '::1');
  assert.equal(clientIP(req('::1', '8.8.8.8, 2001:4860:4860::8888'), ['::1/128']), '2001:4860:4860::8888');
  assert.equal(normalizeIP('::ffff:192.168.1.1'), '192.168.1.1');
  assert.ok(inCIDR('2001:db8:1::1', '2001:db8::/32'));
  assert.throws(() => validateProxies(['10.0.0.0/999']));
  assert.throws(() => validateProxies(['10.0.0.0/']));
  for (const ip of ['10.0.0.3', '172.16.4.2', '192.168.3.2', '::1', 'fd00::20', 'fe80::24', '::ffff:127.0.0.1']) assert.ok(localIP(ip));
  const db = openDatabase(':memory:'); let calls = 0;
  const lookup = locationLookup(db, {}, async (url) => {
    calls++; assert.ok(url.href.startsWith('https://ipwho.is/8.8.8.8?'));
    return new Response(JSON.stringify({ success: true, country: '美国', region: '加利福尼亚州', city: '山景城' }));
  });
  assert.equal((await lookup('127.0.0.1')).kind, 'local'); assert.equal(calls, 0);
  const pair = await Promise.all([lookup('8.8.8.8'), lookup('8.8.8.8')]); assert.equal(calls, 1); assert.equal(pair[0].city, '山景城');
  assert.deepEqual(await lookup('8.8.8.8'), pair[0]); assert.equal(calls, 1);
  const bad = locationLookup(db, {}, async () => { throw new Error('offline'); }); assert.equal((await bad('1.1.1.1')).kind, 'unknown');
  assert.equal(db.prepare('SELECT count(*) AS n FROM ip_locations').get().n, 2);
  db.close();
});

test('migration preserves old records, migrates background defaults and fills publish timestamps', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'moonlit-migration-')); const file = join(directory, 'old.sqlite');
  let db = new DatabaseSync(file);
  db.exec('CREATE TABLE schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL) STRICT;');
  for (const name of ['001-initial.sql', '002-workroom.sql', '003-drafts-and-previews.sql']) { db.exec(await readFile(resolve(root, 'migrations', name), 'utf8')); db.prepare('INSERT INTO schema_migrations VALUES (?, ?)').run(name, '2026-01-01T00:00:00.000Z'); }
  db.prepare('INSERT INTO batches VALUES (?, ?, ?, ?)').run('batch', 'admin:test', '2026-01-01T00:00:00.000Z', 'synced');
  db.prepare('INSERT INTO media (id,name,mime,size,created_at) VALUES (?, ?, ?, ?, ?)').run('old-media', 'old.wav', 'audio/wav', 1, 'old');
  db.prepare('INSERT INTO background_tracks (media_id,created_at) VALUES (?, ?)').run('old-media', 'old');
  db.prepare('INSERT INTO drafts VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)').run('draft', 'background', 'background', 'admin:test', '{"fields":{},"files":{"audio":[]}}', 2, 1, 'draft', 'batch', 'old', 'old');
  db.close(); db = openDatabase(file);
  assert.equal(db.prepare('SELECT synced_at FROM batches').get().synced_at, '2026-01-01T00:00:00.000Z');
  assert.equal(JSON.parse(db.prepare('SELECT document FROM drafts').get().document).fields.volume, '0.05');
  assert.equal(db.prepare('SELECT volume FROM background_tracks').get().volume, .05);
  assert.equal(db.prepare('SELECT name FROM schema_migrations ORDER BY name DESC LIMIT 1').get().name, '008-chat-retention-and-sync.sql'); db.close();
  for (const part of [file, file + '-wal', file + '-shm']) await rm(part, { force: true }); await rmdir(directory);
});

test('global sync is atomic; public batches exclude drafts, deduplicate retries, retain volume after restart', { timeout: 30000 }, async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'moonlit-global-')); const dbPath = join(directory, 'site.sqlite');
  const password = randomBytes(20).toString('hex'); let db = openDatabase(dbPath); await setAdmin(db, 'tester', password); db.close();
  const config = { ...readConfig({ envFile: false }), dbPath, seedDemo: true, host: '127.0.0.1', baseUrl: '', secureCookie: false };
  let server, base, auth;
  const start = async () => { server = await createApplication(config); server.listen(0, '127.0.0.1'); await once(server, 'listening'); base = 'http://127.0.0.1:' + server.address().port; };
  const stop = async () => { server.closeAllConnections(); await new Promise((done) => server.close(done)); };
  t.after(async () => { if (server?.listening) await stop(); for (const file of [dbPath, dbPath + '-wal', dbPath + '-shm']) await rm(file, { force: true }); await rmdir(directory); });
  const request = async (path, json, headers = auth) => { const res = await fetch(base + path, { method: json === undefined ? 'GET' : 'POST', headers: { ...headers, ...(json === undefined ? {} : { 'Content-Type': 'application/json', 'Idempotency-Key': randomUUID() }) }, body: json === undefined ? undefined : JSON.stringify(json) }); return { status: res.status, data: await res.json(), res }; };
  await start(); const login = await request('/api/admin/login', { username: 'tester', password }, {});
  auth = { Cookie: login.res.headers.get('set-cookie').split(';')[0], 'X-CSRF-Token': login.data.csrf };
  assert.equal((await request('/api/admin/drafts/sync-all', { items: [] }, {})).status, 401);
  const bg = (await request('/api/admin/background')).data.item; assert.equal(bg.volume, .05);
  const saved = await request('/api/admin/uploads/background', { fields: { version: bg.version, volume: '0.09' }, files: {} });
  assert.equal(saved.status, 201, JSON.stringify(saved.data));
  const draft = saved.data.item;
  assert.equal((await request('/api/public/background')).data.item.volume, .05);
  assert.equal((await request('/api/public/releases')).data.items.length, 0);
  const q = await request('/api/public/questions', { question: '原子同步验收', anonymous: true }, {});
  const pending = await fetch(base + '/api/admin/questions/' + q.data.id + '/draft', { method: 'PUT', headers: { ...auth, 'Idempotency-Key': randomUUID(), 'Content-Type': 'application/json' }, body: JSON.stringify({ reply: '', version: 0 }) }); const reply = (await pending.json()).item;
  const items = [{ id: draft.draftId, version: draft.version }, { id: reply.draftId, version: reply.version }];
  assert.equal((await request('/api/admin/drafts/sync-all', { items })).status, 400);
  assert.equal((await request('/api/public/background')).data.item.volume, .05, 'one invalid reply rolls back all publishes');
  assert.equal((await request('/api/public/releases')).data.items.length, 0);
  const fixed = await fetch(base + '/api/admin/questions/' + q.data.id + '/draft', { method: 'PUT', headers: { ...auth, 'Idempotency-Key': randomUUID(), 'Content-Type': 'application/json' }, body: JSON.stringify({ reply: '公开回信', version: reply.version }) }); const fixedReply = (await fixed.json()).item;
  items[1].version = fixedReply.version;
  assert.equal((await request('/api/admin/drafts/sync-all', { items })).status, 200);
  assert.equal((await request('/api/public/background')).data.item.volume, .09);
  const releases = (await request('/api/public/releases')).data.items; assert.equal(releases.length, 2);
  assert.ok(releases.every((item) => item.publishedAt && item.batchId && !JSON.stringify(item).includes('admin:')));
  assert.ok(releases.some((item) => item.batchId === draft.batchId));
  await request('/api/admin/drafts/sync-all', { items }); assert.deepEqual((await request('/api/public/releases')).data.items, releases);
  const activity = await request('/api/public/activity', { type: 'page.enter', segmentId: randomUUID(), path: '/', entryPath: '/' }, { 'X-Forwarded-For': '8.8.8.8' });
  assert.equal(activity.status, 200); assert.equal((await request('/api/admin/logs/visitors')).data.items[0].location_kind, 'local');
  await stop(); await start(); assert.equal((await request('/api/public/background')).data.item.volume, .09); assert.deepEqual((await request('/api/public/releases')).data.items, releases);
  let lookups = 0;
  const provider = createServer((req, res) => { lookups++; res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify(req.url.startsWith('/8.8.8.8') ? { success: true, country: '美国', region: '加利福尼亚州', city: '测试城市' } : { success: false })); });
  provider.listen(0, '127.0.0.1'); await once(provider, 'listening');
  t.after(() => new Promise((done) => provider.close(done)));
  await stop(); config.trustedProxies = ['127.0.0.1/32']; config.ipGeoEnabled = true; config.ipGeoEndpoint = 'http://127.0.0.1:' + provider.address().port + '/'; await start();
  const visit = await request('/api/public/activity', { type: 'page.enter', segmentId: randomUUID(), path: '/games', entryPath: '/' }, { 'X-Forwarded-For': '8.8.8.8' });
  const visitor = { Cookie: visit.res.headers.get('set-cookie').split(';')[0], 'X-Forwarded-For': '8.8.8.8' };
  await Promise.all(Array.from({ length: 3 }, () => request('/api/public/activity', { type: 'page.enter', segmentId: randomUUID(), path: '/games', entryPath: '/' }, visitor)));
  const geo = (await request('/api/admin/logs/visitors?path=/games&type=page.enter')).data.items[0];
  assert.equal(geo.location_kind, 'estimated'); assert.equal(geo.country, '美国'); assert.equal(geo.province, '加利福尼亚州'); assert.equal(geo.city, '测试城市'); assert.equal(geo.repeats, 4); assert.equal(lookups, 1);
  await request('/api/public/activity', { type: 'page.enter', segmentId: randomUUID(), path: '/about', entryPath: '/' }, { 'X-Forwarded-For': '1.1.1.1' });
  assert.equal((await request('/api/admin/logs/visitors?path=/about')).data.items[0].location_kind, 'unknown');
  await stop(); await start();
  assert.equal((await request('/api/admin/logs/visitors?path=/games')).data.items[0].city, '测试城市');
});
